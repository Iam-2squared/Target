CREATE FUNCTION target_private.territory_current_season(p_now timestamptz)
RETURNS uuid LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE starts timestamptz:=(date_trunc('week',p_now AT TIME ZONE 'Asia/Tokyo') AT TIME ZONE 'Asia/Tokyo'); season_uuid uuid;
BEGIN
  SELECT id INTO season_uuid FROM target_private.territory_seasons WHERE starts_at=starts;
  IF FOUND THEN RETURN season_uuid; END IF;
  -- The caller owns the shared wallet advisory lock before this allocation.
  IF (SELECT logical_bytes+260000>104857600 FROM target_private.system_state WHERE singleton FOR UPDATE) THEN RAISE EXCEPTION 'Territory capacity exceeded' USING ERRCODE='TQ001'; END IF;
  INSERT INTO target_private.territory_seasons(starts_at,ends_at) VALUES(starts,starts+interval '7 days') RETURNING id INTO season_uuid;
  INSERT INTO target_private.territory_tiles(season_id,x,y,kind,hq_slot,troops)
    SELECT season_uuid,gx,gy,CASE WHEN homes.slot IS NOT NULL THEN 1 WHEN castles.x IS NOT NULL THEN 2 ELSE 0 END,homes.slot,CASE WHEN castles.x IS NOT NULL THEN 8 ELSE 0 END
    FROM generate_series(0,49)gx CROSS JOIN generate_series(0,49)gy
    LEFT JOIN (SELECT n AS slot,3+(n-1)%8*6 AS x,5+(n-1)/8*10 AS y FROM generate_series(1,40)n)homes ON homes.x=gx AND homes.y=gy
    LEFT JOIN (VALUES(12,12),(37,12),(25,25),(12,37),(37,37))castles(x,y) ON castles.x=gx AND castles.y=gy;
  UPDATE target_private.system_state SET logical_bytes=logical_bytes+260000 WHERE singleton;
  RETURN season_uuid;
END $$;

