    'season',jsonb_build_object('id',to_char(s.starts_at AT TIME ZONE 'Asia/Tokyo','YYYY-MM-DD'),'startsAt',s.starts_at,'endsAt',s.ends_at),
    'serverNow',p_now,'revision',s.revision,'summaryMinute',floor(extract(epoch FROM p_now)/60)::bigint,'selfSlot',(SELECT slot FROM target_private.territory_players WHERE season_id=p_season AND member_id=p_member),
    'players',CASE WHEN p_cache_season=to_char(s.starts_at AT TIME ZONE 'Asia/Tokyo','YYYY-MM-DD') AND p_cache_revision=s.revision AND p_cache_minute=floor(extract(epoch FROM p_now)/60)::bigint THEN NULL ELSE coalesce((SELECT jsonb_agg(jsonb_build_object('slot',r.slot,'memberId',r.member_id,'name',r.name,'home',jsonb_build_object('x',3+(r.slot-1)%8*6,'y',5+(r.slot-1)/8*10),
