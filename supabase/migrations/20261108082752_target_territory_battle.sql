CREATE FUNCTION target_private.territory_normalize_command(p_command jsonb)
RETURNS jsonb LANGUAGE plpgsql IMMUTABLE STRICT SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE kind text; keys text[]; key text; n numeric;
BEGIN
  IF jsonb_typeof(p_command) IS DISTINCT FROM 'object' THEN RAISE EXCEPTION 'Invalid command' USING ERRCODE='22023'; END IF;
  kind:=p_command->>'type';
  keys:=CASE kind WHEN 'join' THEN ARRAY['type'] WHEN 'claim' THEN ARRAY['type','x','y','expectedTargetVersion']
    WHEN 'reinforce' THEN ARRAY['type','x','y','troops','expectedTargetVersion']
    WHEN 'move' THEN ARRAY['type','fromX','fromY','x','y','troops','expectedSourceVersion','expectedTargetVersion']
    WHEN 'attack' THEN ARRAY['type','fromX','fromY','x','y','troops','expectedSourceVersion','expectedTargetVersion'] ELSE NULL END;
  IF keys IS NULL OR NOT(p_command?&keys) OR (SELECT count(*) FROM jsonb_object_keys(p_command))<>cardinality(keys) THEN RAISE EXCEPTION 'Invalid command' USING ERRCODE='22023'; END IF;
  FOREACH key IN ARRAY keys LOOP
    IF key='type' THEN CONTINUE; END IF;
    IF jsonb_typeof(p_command->key) IS DISTINCT FROM 'number' OR coalesce(p_command->>key,'')!~'^(0|[1-9][0-9]{0,15})$' THEN RAISE EXCEPTION 'Invalid command value' USING ERRCODE='22023'; END IF;
    n:=(p_command->>key)::numeric;
    IF (key IN ('x','y','fromX','fromY') AND n NOT BETWEEN 0 AND 49) OR (key='troops' AND n NOT BETWEEN 1 AND 1000) OR
       (key IN ('expectedSourceVersion','expectedTargetVersion') AND n>9007199254740991) THEN RAISE EXCEPTION 'Invalid command bounds' USING ERRCODE='22023'; END IF;
  END LOOP;
  RETURN p_command;
END $$;

-- A pure plan evaluated while the caller owns the shared wallet/season locks.
-- It neither joins a player nor consumes money, troops, a revision or a UUID.
CREATE FUNCTION target_private.territory_plan(p_member uuid,p_season uuid,p_command jsonb)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE player target_private.territory_players%ROWTYPE; target target_private.territory_tiles%ROWTYPE; source target_private.territory_tiles%ROWTYPE;
  kind text:=p_command->>'type'; assigned integer; amount integer:=0; sent integer; remaining_source integer:=NULL; remaining_target integer; owner integer; outcome text;
BEGIN
  SELECT * INTO player FROM target_private.territory_players WHERE season_id=p_season AND member_id=p_member;
  IF kind='join' THEN
    IF player.slot IS NOT NULL THEN
      assigned:=player.slot;
      SELECT troops INTO remaining_target FROM target_private.territory_tiles WHERE season_id=p_season AND hq_slot=assigned;
    ELSE
      SELECT min(n) INTO assigned FROM generate_series(1,40)n WHERE NOT EXISTS(SELECT 1 FROM target_private.territory_players WHERE season_id=p_season AND slot=n);
      IF assigned IS NULL THEN RETURN target_private.error_result(409,'PLAYER_LIMIT','今シーズンの参加人数は40人です。'); END IF;
      remaining_target:=10;
    END IF;
    RETURN jsonb_build_object('cost',0,'preview',jsonb_build_object('result','joined','sourceRemaining',NULL,'targetRemaining',remaining_target,'targetOwnerSlot',assigned));
  END IF;
  IF player.slot IS NULL THEN RETURN target_private.error_result(409,'NOT_JOINED','参戦してから操作してください。'); END IF;
  SELECT * INTO target FROM target_private.territory_tiles WHERE season_id=p_season AND x=(p_command->>'x')::integer AND y=(p_command->>'y')::integer;
  IF target.version<>(p_command->>'expectedTargetVersion')::bigint THEN RETURN target_private.error_result(409,'BOARD_CHANGED','選択したマスが変わりました。確認してください。'); END IF;
  IF kind IN ('move','attack') THEN
    SELECT * INTO source FROM target_private.territory_tiles WHERE season_id=p_season AND x=(p_command->>'fromX')::integer AND y=(p_command->>'fromY')::integer;
    IF source.version<>(p_command->>'expectedSourceVersion')::bigint THEN RETURN target_private.error_result(409,'BOARD_CHANGED','出兵元が変わりました。確認してください。'); END IF;
    IF source.owner_slot IS DISTINCT FROM player.slot THEN RETURN target_private.error_result(409,'NOT_OWNER','自分の領土を選んでください。'); END IF;
    IF abs(source.x-target.x)+abs(source.y-target.y)<>1 THEN RETURN target_private.error_result(409,'NOT_ADJACENT','上下左右につながるマスを選んでください。'); END IF;
    sent:=(p_command->>'troops')::integer;
    IF source.troops<=sent THEN RETURN target_private.error_result(409,'INSUFFICIENT_TROOPS','出兵元には1兵以上残してください。'); END IF;
    remaining_source:=source.troops-sent;
  END IF;
  IF kind='claim' THEN
    IF target.kind=1 THEN RETURN target_private.error_result(409,'HQ_PROTECTED','本拠地は保護されています。'); END IF;
    IF target.kind<>0 OR target.owner_slot IS NOT NULL OR target.troops<>0 THEN RETURN target_private.error_result(409,'INVALID_TARGET','空いている通常マスを選んでください。'); END IF;
    IF NOT EXISTS(SELECT 1 FROM target_private.territory_tiles t WHERE t.season_id=p_season AND t.owner_slot=player.slot AND abs(t.x-target.x)+abs(t.y-target.y)=1) THEN RETURN target_private.error_result(409,'NOT_ADJACENT','自分の領土につながるマスを選んでください。'); END IF;
    amount:=1000;remaining_target:=1;owner:=player.slot;outcome:='claimed';
  ELSIF kind='reinforce' THEN
    IF target.owner_slot IS DISTINCT FROM player.slot THEN RETURN target_private.error_result(409,'NOT_OWNER','自分の領土を選んでください。'); END IF;
    remaining_target:=target.troops+(p_command->>'troops')::integer;
    IF remaining_target>1000 THEN RETURN target_private.error_result(409,'TROOP_LIMIT','1マスの兵力は1,000までです。'); END IF;
    amount:=(p_command->>'troops')::integer*1000;owner:=player.slot;outcome:='reinforced';
  ELSIF kind='move' THEN
    IF target.owner_slot IS DISTINCT FROM player.slot THEN RETURN target_private.error_result(409,'NOT_OWNER','移動先も自分の領土を選んでください。'); END IF;
    remaining_target:=target.troops+sent;
    IF remaining_target>1000 THEN RETURN target_private.error_result(409,'TROOP_LIMIT','移動先の兵力は1,000までです。'); END IF;
    owner:=player.slot;outcome:='moved';
  ELSIF kind='attack' THEN
    IF target.kind=1 THEN RETURN target_private.error_result(409,'HQ_PROTECTED','本拠地は保護されています。'); END IF;
    IF target.owner_slot=player.slot OR (target.owner_slot IS NULL AND target.kind<>2) THEN RETURN target_private.error_result(409,'INVALID_TARGET','敵の領土か城を選んでください。'); END IF;
    amount:=1000;
    IF sent>target.troops THEN remaining_target:=sent-target.troops;owner:=player.slot;outcome:='captured';
    ELSIF sent<target.troops THEN remaining_target:=target.troops-sent;owner:=coalesce(target.owner_slot,0);outcome:='defended';
    ELSE remaining_target:=0;owner:=0;outcome:='neutralized'; END IF;
  ELSE RETURN target_private.error_result(400,'INVALID_REQUEST','操作を確認してください。');
  END IF;
  RETURN jsonb_build_object('cost',amount,'preview',jsonb_build_object('result',outcome,'sourceRemaining',remaining_source,'targetRemaining',remaining_target,'targetOwnerSlot',owner));
END $$;

CREATE FUNCTION target_private.territory_accrue(p_season uuid,p_slot integer,p_now timestamptz)
RETURNS void LANGUAGE sql SECURITY INVOKER SET search_path=pg_catalog AS $$
  UPDATE target_private.territory_players p SET
    score_millis=p.score_millis+greatest(0,floor(extract(epoch FROM (least(p_now,s.ends_at)-p.accrued_at))*1000)::bigint)*(p.land_count+9*p.castle_count),
    accrued_at=greatest(p.accrued_at,least(p_now,s.ends_at))
  FROM target_private.territory_seasons s WHERE p.season_id=p_season AND p.slot=p_slot AND s.id=p.season_id;
$$;

