CREATE TABLE target_private.territory_players (
  season_id uuid NOT NULL REFERENCES target_private.territory_seasons(id),
  member_id uuid NOT NULL REFERENCES target_private.profiles(member_id),
  slot smallint NOT NULL CHECK(slot BETWEEN 1 AND 40),
  land_count integer NOT NULL DEFAULT 1 CHECK(land_count BETWEEN 1 AND 2500),
  castle_count integer NOT NULL DEFAULT 0 CHECK(castle_count BETWEEN 0 AND 5 AND castle_count<=land_count),
  score_millis bigint NOT NULL DEFAULT 0 CHECK(score_millis BETWEEN 0 AND 1000000000000000),
  accrued_at timestamptz NOT NULL,
  joined_at timestamptz NOT NULL,
  PRIMARY KEY(season_id,member_id),
  UNIQUE(season_id,slot)
);
CREATE TABLE target_private.territory_tiles (
  season_id uuid NOT NULL REFERENCES target_private.territory_seasons(id),
  x smallint NOT NULL CHECK(x BETWEEN 0 AND 49),
  y smallint NOT NULL CHECK(y BETWEEN 0 AND 49),
  kind smallint NOT NULL CHECK(kind BETWEEN 0 AND 2),
  hq_slot smallint CHECK(hq_slot BETWEEN 1 AND 40),
  owner_slot smallint,
  troops smallint NOT NULL DEFAULT 0 CHECK(troops BETWEEN 0 AND 1000),
  version bigint NOT NULL DEFAULT 0 CHECK(version BETWEEN 0 AND 10000000000000),
  PRIMARY KEY(season_id,x,y),
  FOREIGN KEY(season_id,owner_slot) REFERENCES target_private.territory_players(season_id,slot),
  CHECK((kind=1)=(hq_slot IS NOT NULL)),
  CHECK(owner_slot IS NULL OR troops>=1),
  CHECK(owner_slot IS NOT NULL OR troops=0 OR kind=2),
  CHECK(kind<>1 OR owner_slot IS NULL OR owner_slot=hq_slot)
);
